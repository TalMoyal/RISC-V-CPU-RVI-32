module instruction_memory (
    input  logic [31:0] address,
    output logic [31:0] instruction
);


    // 256 words, each 32 bits wide
    logic [31:0] memory [0:255];


    initial begin


    memory[0] = 32'b000000000101_00000_000_00001_0010011; // ADDI x1, x0, 5
    memory[1] = 32'b000000000101_00000_000_00010_0010011; // ADDI x2, x0, 5
    memory[2] = 32'b0000000_00010_00001_000_0100_0_1100011; // BEQ x1, x2, +8
    memory[3] = 32'b000001100011_00000_000_00101_0010011; // ADDI x5, x0, 99
    memory[4] = 32'b000000101010_00000_000_00110_0010011; // ADDI x6, x0, 42



    end

    assign instruction = memory[address[9:2]];

endmodule

